// Package site serves the public website: server-rendered pages built from
// the database, the static assets, and uploaded images.
package site

import (
	"bytes"
	"crypto/sha256"
	"database/sql"
	"embed"
	"encoding/hex"
	"fmt"
	"html/template"
	"io/fs"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/mlh5599/muddys-music-cafe/server/internal/storage"
)

//go:embed templates/*.html
var templateFS embed.FS

//go:embed static
var staticFS embed.FS

// Config holds what the site needs to run.
type Config struct {
	DB         *sql.DB
	UploadsDir string
	// SiteURL is the public origin (e.g. https://example.com), used to make
	// link-preview image addresses absolute. Empty keeps them relative.
	SiteURL string
	// Now returns the current time; nil means time.Now. Tests override it.
	Now func() time.Time
}

// Site is the public site handler.
type Site struct {
	cfg      Config
	events   *storage.EventStore
	staff    *storage.StaffStore
	partners *storage.PartnerStore
	settings *storage.SettingsStore
	images   *storage.ImageStore

	home, staffPage *template.Template
	version         string
	listeners       chan struct{}
	mux             *http.ServeMux
}

// New builds the site handler.
func New(cfg Config) (*Site, error) {
	if cfg.Now == nil {
		cfg.Now = time.Now
	}
	s := &Site{
		cfg:       cfg,
		events:    storage.NewEventStore(cfg.DB),
		staff:     storage.NewStaffStore(cfg.DB),
		partners:  storage.NewPartnerStore(cfg.DB),
		settings:  storage.NewSettingsStore(cfg.DB),
		images:    storage.NewImageStore(cfg.DB),
		listeners: make(chan struct{}, maxListeners),
	}
	var err error
	if s.home, err = parseTemplate("home.html"); err != nil {
		return nil, err
	}
	if s.staffPage, err = parseTemplate("staff.html"); err != nil {
		return nil, err
	}
	if s.version, err = staticVersion(); err != nil {
		return nil, err
	}

	s.mux = http.NewServeMux()
	s.mux.HandleFunc("GET /{$}", s.serveHome)
	s.mux.HandleFunc("GET /djs", s.serveStaff(storage.StaffKindDJ))
	s.mux.HandleFunc("GET /hosts", s.serveStaff(storage.StaffKindHost))
	s.mux.Handle("GET /static/", s.staticHandler())
	s.mux.HandleFunc("GET "+radioPath, s.serveRadio)
	s.mux.HandleFunc("GET /uploads/{name}", s.serveUpload)
	s.mux.HandleFunc("/", http.NotFound)
	return s, nil
}

func (s *Site) ServeHTTP(w http.ResponseWriter, r *http.Request) { s.mux.ServeHTTP(w, r) }

func parseTemplate(page string) (*template.Template, error) {
	t, err := template.ParseFS(templateFS, "templates/layout.html", "templates/"+page)
	if err != nil {
		return nil, fmt.Errorf("site: parse %s: %w", page, err)
	}
	return t, nil
}

// staticVersion hashes the embedded static files so asset URLs change (and
// browsers refetch) whenever the assets do.
func staticVersion() (string, error) {
	h := sha256.New()
	err := fs.WalkDir(staticFS, "static", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		b, err := staticFS.ReadFile(p)
		if err != nil {
			return err
		}
		h.Write([]byte(p))
		h.Write(b)
		return nil
	})
	if err != nil {
		return "", fmt.Errorf("site: hash static files: %w", err)
	}
	return hex.EncodeToString(h.Sum(nil))[:10], nil
}

func (s *Site) staticHandler() http.Handler {
	fileServer := http.FileServerFS(staticFS)
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Cache-Control", "public, max-age=31536000, immutable")
		fileServer.ServeHTTP(w, r)
	})
}

// serveUpload serves one uploaded image. Filenames are generated by the server
// and unique, so the response can be cached forever.
func (s *Site) serveUpload(w http.ResponseWriter, r *http.Request) {
	name := r.PathValue("name")
	switch strings.ToLower(filepath.Ext(name)) {
	case ".jpg", ".jpeg", ".png", ".webp", ".gif":
	default:
		http.NotFound(w, r)
		return
	}
	if name != filepath.Base(name) || strings.HasPrefix(name, ".") {
		http.NotFound(w, r)
		return
	}
	f, err := os.Open(filepath.Join(s.cfg.UploadsDir, name))
	if err != nil {
		http.NotFound(w, r)
		return
	}
	defer f.Close()
	fi, err := f.Stat()
	if err != nil || fi.IsDir() {
		http.NotFound(w, r)
		return
	}
	w.Header().Set("Cache-Control", "public, max-age=31536000, immutable")
	http.ServeContent(w, r, name, fi.ModTime(), f)
}

// render executes the page into a buffer first, so a template error produces a
// clean 500 instead of a half-written page, then writes it with a content
// hash ETag so unchanged pages answer 304.
func (s *Site) render(w http.ResponseWriter, r *http.Request, t *template.Template, page string, data any) {
	var buf bytes.Buffer
	if err := t.ExecuteTemplate(&buf, page, data); err != nil {
		log.Printf("site: render %s: %v", r.URL.Path, err)
		http.Error(w, "Something went wrong. Please try again.", http.StatusInternalServerError)
		return
	}
	sum := sha256.Sum256(buf.Bytes())
	etag := `"` + hex.EncodeToString(sum[:8]) + `"`
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	w.Header().Set("Cache-Control", "no-cache")
	w.Header().Set("ETag", etag)
	if r.Header.Get("If-None-Match") == etag {
		w.WriteHeader(http.StatusNotModified)
		return
	}
	_, _ = w.Write(buf.Bytes())
}

func (s *Site) fail(w http.ResponseWriter, r *http.Request, err error) {
	log.Printf("site: %s: %v", r.URL.Path, err)
	http.Error(w, "Something went wrong. Please try again.", http.StatusInternalServerError)
}
